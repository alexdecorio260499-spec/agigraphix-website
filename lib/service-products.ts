export function getSubcategoriesForService(slug: string): { id: string; label: string; count: number }[] {
  const products = getProductsByService(slug);
  const subMap = new Map<string, { id: string; label: string; count: number }>();
  
  for (const p of products) {
    const existing = subMap.get(p.subcategoryId);
    if (existing) {
      existing.count += 1;
    } else {
      subMap.set(p.subcategoryId, {
        id: p.subcategoryId,
        label: p.subcategoryLabel,
        count: 1,
      });
    }
  }
  
  return Array.from(subMap.values());
}
